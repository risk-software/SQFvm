#pragma once
#include "../runtime/value.h"

#include <string_view>

namespace sqf
{
    namespace runtime
    {
        class runtime;
    }

    namespace operators
    {
        /// Type of the default value that a simulated command returns, from the wiki's return type.
        enum class simulated_return
        {
            nothing, boolean, number, string, array, color, position, object, group, side, config, text,
            hashmap, display, control, task, location, teammember, diaryrecord, script, namespace_, code
        };

        /// Logs once per command that it is simulated and returns the default value of the given type.
        ::sqf::runtime::value simulated_result(::sqf::runtime::runtime& runtime, std::string_view command, simulated_return type);

        /// Null values and isNull for the handle types (location, display, control, task, team member,
        /// diary record, net object). Loaded before ops_simulated.
        void ops_simulated_support(::sqf::runtime::runtime& runtime);

        /// Generated by tools/generate_simulated_ops.py: every command syntax from the Arma 3 wiki data
        /// that has no real implementation, with its argument types and a default return value.
        /// Must be loaded after all real operators, as it only registers syntaxes that are still free.
        void ops_simulated(::sqf::runtime::runtime& runtime);
    }
}
